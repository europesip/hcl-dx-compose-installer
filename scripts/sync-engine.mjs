#!/usr/bin/env node
// Extracts the option C engine (direct installation) of the configuration wizard of
// hcl-dx-compose-labs (docs/index.html) into src/engine/wizard-engine.js.
//
// The wizard is the single source of truth: validation messages, the lab files (TPL), how every
// file is filled in with the user's values, the list of steps, RUNBOOK.md, install.sh and the zip.
// This app only adds its own interface and the Word guide on top. Run it whenever the labs change:
//
//   npm run sync-engine                                   (../dx-compose-webinar/docs/index.html)
//   npm run sync-engine -- /path/to/hcl-dx-compose-labs/docs/index.html
//   npm run sync-engine -- --check                        (exit 1 if the engine is out of date)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const check = args.includes("--check");
const candidates = [args.find(a => !a.startsWith("--")), process.env.LABS_WIZARD,
  resolve(here, "../../dx-compose-webinar/docs/index.html"), resolve(here, "../../hcl-dx-compose-labs/docs/index.html")].filter(Boolean);
const src = candidates.find(p => existsSync(p));
if (!src) { console.error("Wizard not found. Pass the path of hcl-dx-compose-labs/docs/index.html"); process.exit(2); }

const html = readFileSync(src, "utf8");
const script = html.slice(html.indexOf("<script>") + 8, html.lastIndexOf("</script>"));
const lines = script.split("\n");
const from = lines.findIndex(l => l.startsWith("// Messages generated by the script"));
const to = lines.findIndex(l => l.startsWith("// After a download"));
if (from < 0 || to < 0) { console.error("Engine markers not found in " + src + ": the wizard layout changed"); process.exit(3); }
// The block ends with a separator line before "After a download": drop it
let body = lines.slice(from, to).join("\n").replace(/\n\/\/ -{20,}\s*$/, "\n");
for (const need of ["function validate(", "function bundleFiles(", "function directSteps(", "function buildDirectRunbook(",
                    "function buildDirectZip(", "function zip(", "const ORBITA_VERSION", "const TPL = {", "let litellmKey"])
  if (!body.includes(need)) { console.error(`"${need}" not found: the wizard layout changed`); process.exit(3); }
const sha = createHash("sha256").update(html).digest("hex").slice(0, 12);

const out = `// GENERATED by scripts/sync-engine.mjs from the configuration wizard of hcl-dx-compose-labs
// (docs/index.html, sha256 ${sha}). Do not edit by hand: change the wizard and run npm run sync-engine.
// It is the option C engine: validation, lab files filled in with the user's values, steps,
// RUNBOOK.md, install.sh, uninstall.sh and the zip. Everything runs in the browser.
/* eslint-disable */
export const ENGINE_SOURCE_SHA = "${sha}";
export function createEngine(){
${body}
  return {
    setLang(l){ lang = l === "es" ? "es" : "en"; },
    validate, bundleFiles, directSteps, buildDirectRunbook, buildInstallSh, buildUninstallSh, buildDirectZip, zip,
    pgSqlFor, ORBITA_VERSION, TPL, DESC, PH,
    get litellmKey(){ return litellmKey; },
    ensureLitellmKey(){ if (!litellmKey) litellmKey = randomKey(); return litellmKey; },
  };
}
`;
const target = resolve(here, "../src/engine/wizard-engine.js");
if (check) {
  const cur = existsSync(target) ? readFileSync(target, "utf8") : "";
  if (cur !== out) { console.error(`Engine out of date (wizard sha ${sha}): run npm run sync-engine`); process.exit(1); }
  console.log(`Engine up to date (wizard sha ${sha})`); process.exit(0);
}
writeFileSync(target, out);
console.log(`src/engine/wizard-engine.js written from ${src} (sha ${sha}, ${body.split("\n").length} lines)`);
