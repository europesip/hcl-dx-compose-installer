// demo.sh: Helm asks for the password at the terminal; without one (unattended run), it is read from the pull secret
export function harborPromptDemo(text, sops){
  return text.replace(new RegExp(`^helm registry login (\\S+) -u (\\S+)   ${PROMPT_COMMENT.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}$`, "m"), (_, host, user) => {
    const read = sops ? `sops -d --extract '["stringData"][".dockerconfigjson"]' lab-base/secret-harbor.yaml`
                      : `kubectl create --dry-run=client -f lab-base/secret-harbor.yaml -o jsonpath='{.stringData.\\.dockerconfigjson}'`;
    return `hlogin() {   # Helm asks for the CLI secret; without a terminal (unattended run) it is read from the pull secret
  if [ -t 0 ]; then helm registry login ${host} -u ${user}
  else ${read} | python3 -c 'import json,sys; print(next(iter(json.load(sys.stdin)["auths"].values()))["password"])' | helm registry login ${host} -u ${user} --password-stdin; fi
}
retry hlogin`;
  }).replace(/^sops -d -i lab-base\/secrets\.yaml$/m, "grep -q '^sops:' lab-base/secrets.yaml && sops -d -i lab-base/secrets.yaml   # decrypted once, then it stays in clear text");
}

