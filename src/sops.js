// The base secrets of the webinar as in the webinar of 2026-11-12 (#17), output layer (the engine stays as the
// golden test expects):
//   - the pull secret in its own file, lab-base/secret-harbor.yaml, and wpsadmin in lab-base/secrets.yaml;
//   - the HCL Harbor sign-in of step 0-3 with the user on the command line and the password typed at the prompt
//     (demo.sh reads it from the pull secret only when it runs without a terminal);
//   - optional SOPS (age): only PUBLIC keys are asked for, one or more. The wizard writes .sops.yaml and the
//     commands; the real sops CLI encrypts the files on the user's machine (prepare.sh). No private key ever goes
//     through the wizard, and nothing leaves the browser.

export const SOPS_FILES = ["lab-base/secret-harbor.yaml", "lab-base/secrets.yaml"];
const AGE_PUBLIC = /^age1[02-9ac-hj-np-z]{58}$/;
const AGE_PRIVATE = /AGE-SECRET-KEY-1/i;

export const sopsOn = f => f.preset === "webinar" && !!f.sops;

// "name age1..." or "age1...", one per line (# comments and empty lines are ignored). Duplicates are dropped.
export function parseSopsKeys(text){
  const keys = [], bad = [];
  let privateKey = false;
  for (const raw of String(text || "").split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    if (AGE_PRIVATE.test(line)) { privateKey = true; continue; }
    const words = line.split(/\s+/), key = words[words.length - 1];
    if (!AGE_PUBLIC.test(key)) { bad.push(line.length > 24 ? line.slice(0, 24) + "…" : line); continue; }
    const name = words.slice(0, -1).join(" ").replace(/[^\w .@-]/g, "").slice(0, 40);
    if (!keys.some(k => k.key === key)) keys.push({name, key});
  }
  return {keys, bad, privateKey};
}

export function sopsErrors(f, lang){
  if (!sopsOn(f)) return [];
  const es = lang === "es", {keys, bad, privateKey} = parseSopsKeys(f.SOPS_KEYS);
  const err = [];
  if (privateKey) err.push(es ? "SOPS: has pegado una clave PRIVADA de age (AGE-SECRET-KEY-1…). Bórrala: aquí solo van las claves públicas (age1…), la privada no sale de tu equipo."
                              : "SOPS: you pasted a PRIVATE age key (AGE-SECRET-KEY-1…). Delete it: only public keys (age1…) go here, the private one never leaves your machine.");
  if (bad.length) err.push(es ? `SOPS: no es una clave pública de age válida: ${bad.join(", ")}` : `SOPS: not a valid age public key: ${bad.join(", ")}`);
  if (!keys.length && !privateKey) err.push(es ? "SOPS: indica al menos una clave pública de age (age1…)." : "SOPS: enter at least one age public key (age1…).");
  return err;
}

const splitDocs = text => { const parts = text.split(/^---\s*$/m); return {head: parts[0], docs: parts.slice(1)}; };

// lab-base/secrets.yaml -> secret-harbor.yaml (regcred) + secrets.yaml (wpsadmin); .sops.yaml with SOPS
export function baseSecretFiles(files, s, {sops = false, keys = []} = {}){
  const sec = files["lab-base/secrets.yaml"];
  if (!sec) return files;
  const {docs} = splitDocs(sec.text);
  const harbor = docs.find(d => /^\s*name:\s*regcred\s*$/m.test(d)), rest = docs.filter(d => d !== harbor);
  if (!harbor || !rest.length) return files;
  const hdr = sops
    ? `# Generated by the configuration wizard for ${s.DX_HOST}. prepare.sh encrypts its values with SOPS (age), see .sops.yaml;\n# until then they are in PLAIN TEXT: keep it private.\n`
    : `# Generated by the configuration wizard for ${s.DX_HOST}. Contains credentials in PLAIN TEXT: keep it private.\n`;
  const out = {...files,
    "lab-base/secret-harbor.yaml": {...sec, text: "# lab-base secret: pull secret for hclcr.io (your personal HCL Harbor user and CLI secret)\n" + hdr + "---" + harbor.replace(/\s*$/, "\n")},
    "lab-base/secrets.yaml": {...sec, text: "# lab-base secret: wpsadmin credentials\n" + hdr + rest.map(d => "---" + d.replace(/\s*$/, "\n")).join("")}};
  const cv = out["lab-base/custom-values.yaml"];
  if (cv) out["lab-base/custom-values.yaml"] = {...cv, text: cv.text.replace("# in lab-base/secrets.yaml", "# in lab-base/secret-harbor.yaml")};
  if (sops) out[".sops.yaml"] = {text: sopsYaml(keys), mode: 0o100644};
  return out;
}

export function sopsYaml(keys){
  const w = Math.max(...keys.map(k => (k.name || "-").length));
  return `# SOPS rules: which files are encrypted, which fields, and for which keys.
# Only data and stringData are encrypted: names, namespaces and types stay readable in Git.
# Any of these public keys can decrypt, each one with its own private key (~/.config/sops/age/keys.txt):
${keys.map(k => `#   ${(k.name || "-").padEnd(w)}  ${k.key}`).join("\n")}
# To add or remove a key: edit the list below, then run "sops updatekeys -y <file>" on each encrypted file.
# To encrypt a file again after "sops -d -i": sops -e -i <file>
creation_rules:
  - path_regex: lab-base/(secret-harbor|secrets)\\.yaml$
    encrypted_regex: '^(data|stringData)$'
    age: >-
${keys.map((k, i) => `      ${k.key}${i < keys.length - 1 ? "," : ""}`).join("\n")}
`;
}

