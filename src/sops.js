// Step 1-1: the two files, with SOPS or plain
export function secretsStepCmd(cmd, sops){
  const now = "kubectl apply -f lab-base/secrets.yaml\n";
  if (!cmd.includes(now)) return cmd;
  return cmd.replace(now, sops
    ? `# The two secrets of the base are encrypted with SOPS: names readable, values ENC[AES256_GCM,...]
cat lab-base/secret-harbor.yaml
# Pull secret: decrypted on the fly and applied; the clear value never touches the disk
sops -d lab-base/secret-harbor.yaml | kubectl apply -f -
# wpsadmin: decrypted in place, so it stays in clear text for the rest of the labs, then applied
sops -d -i lab-base/secrets.yaml
kubectl apply -f lab-base/secrets.yaml
`
    : "kubectl apply -f lab-base/secret-harbor.yaml\nkubectl apply -f lab-base/secrets.yaml\n");
}
