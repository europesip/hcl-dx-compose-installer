// Supportability of the generated folder (output layer: the engine stays as the golden test expects):
//   - BUILD-INFO.txt: what the folder was generated for (installer version, platform, Ingress, Helm, options),
//     without secrets, so that support only has to ask for this file;
//   - the same summary in one line at the top of the scripts and the RUNBOOK;
//   - an optional step that checks the access to DX layer by layer (HAProxy, Ingress controller, ports
//     80/443, DNS) with kubectl port-forward, to tell a DX problem from a network one;
//   - support/environment-info.sh: workstation, tools, cluster, Ingress and access, read-only; the support
//     collector (install.sh --collect) includes it, with BUILD-INFO.txt.

/* global __APP_VERSION__, __BUILD_TIME__ */
export const APP_VERSION = typeof __APP_VERSION__ === "string" ? __APP_VERSION__ : "dev";
export const BUILD_TIME = typeof __BUILD_TIME__ === "string" ? __BUILD_TIME__ : "";

const ENV = {own: "own cluster", wsl: "local PC (WSL)", linux: "local PC (Linux)", aws: "AWS"};
const AWS = {ec2: "EC2 + k3s", eks: "Amazon EKS", rosa: "Red Hat OpenShift on AWS (ROSA)"};
const PLATFORM = {kubernetes: "Kubernetes", openshift: "OpenShift", poc: "single-node PoC (k3s on WSL)"};
const exposeFile = s => s.openshift ? "lab-base/route-dx-openshift.yaml"
  : s.INGRESS_CLASS === "traefik" ? "lab-base/ingressroute-dx-traefik.yaml" : "lab-base/ingress-dx.yaml";
export const ingressOf = s => s.openshift ? "OpenShift router (Route)"
  : s.INGRESS_CLASS === "traefik" ? "Traefik (IngressRoute)" : s.INGRESS_CLASS === "nginx" ? "ingress-nginx (Ingress)" : `IngressClass ${s.INGRESS_CLASS} (Ingress with nginx annotations)`;

// The one-line summary used at the top of the scripts and the RUNBOOK
export const stampOf = s => `installer v${APP_VERSION} · ${PLATFORM[s.platform] || s.platform} · ${ingressOf(s)} · Helm ${s.helm === "3" ? 3 : 4}`;

export function buildInfo(form, s, steps, {webinar, vault, cicd, lang, now}){
  const yes = (v, txt) => v ? txt : null;
  const env = form.envSource === "aws" ? `AWS · ${AWS[form.awsKind] || form.awsKind}` : ENV[form.envSource] || "not stated";
  const cmds = steps.map(x => x.cmd || "").join("\n");
  const hcl = [...new Set([...cmds.matchAll(/charts\/(hcl-dx-[a-z-]+?-\d[\w.-]*?)\.tgz/g)].map(m => m[1]))];
  const third = [...new Set([...cmds.matchAll(/upgrade --install (\S+) (\S+) (?:[^\n]*?)--version (\S+)/g)].map(m => `${m[2]} ${m[3]}`))];
  const stages = [...new Set(steps.map(x => x.lab).filter(Boolean))];
  const extras = [yes(form.lab1b, "Script Application (Hello DX)"), yes(s.lab3b, "EUROPESIP MCP server"), yes(s.iqdb, "IQ sessions and memory in PostgreSQL"),
    yes(s.iqrag, "IQ RAG (pgvector)"), yes(form.keycloak, "Keycloak SSO"), yes(form.cicdOpenbao || vault, "OpenBao + External Secrets"),
    yes(form.cicdArgo, "Argo CD"), yes(form.cicdOperator, "Script Application operator"), yes(form.altRegistry, `own image registry (${(form.REGISTRY || "").trim()})`)].filter(Boolean);
  const L = [
    "# BUILD-INFO.txt · what this folder was generated for, by the HCL DX Compose Installer.",
    "# It contains no passwords, keys or tokens. If something fails, send this file (./install.sh --collect includes it).",
    "",
    `installer.version : ${APP_VERSION}${BUILD_TIME ? ` (built ${BUILD_TIME.slice(0, 16).replace("T", " ")} UTC)` : ""}`,
    `generated         : ${now} UTC`,
    `language          : ${lang}`,
    `deployment        : ${webinar ? "webinar (prepare.sh + demo.sh)" : `installation (install.sh)${form.preset ? ` · preset ${form.preset}` : ""}`}`,
    `environment       : ${env}`,
    `platform          : ${PLATFORM[s.platform] || s.platform}`,
    `ingress           : ${ingressOf(s)} · applied with ${exposeFile(s)}`,
    `helm              : ${s.helm === "3" ? "3 (--wait)" : "4 (--wait=legacy, --force-conflicts)"} · the scripts adapt the flags to the Helm they find`,
    `dx.url            : https://${s.DX_HOST}/wps/portal`,
    `tls               : ${s.TLS_CERT ? "own certificate" : "self-signed (generated by the scripts)"}`,
    `namespaces        : ${s.DX_NS} (HCL) · ${s.SHARED_NS} (third party)`,
    `releases          : DX ${s.DX_RELEASE} · IQ ${s.IQ_RELEASE} · search ${s.SEARCH_RELEASE} · OpenLDAP ${s.LDAP_RELEASE} · LiteLLM ${s.LITELLM_RELEASE} · PostgreSQL ${s.PG_CLUSTER}`,
    `storage           : ${s.SC_RWO} (ReadWriteOnce) · ${s.SC_RWX} (ReadWriteMany)`,
    `directory         : ${s.dir === "ad" ? "Active Directory" : "OpenLDAP (demo users)"}`,
    `database          : ${s.db === "postgres" ? "PostgreSQL (CloudNativePG)" : s.db === "oracle" ? "Oracle" : "Derby (built-in)"}`,
    `ai                : ${s.lab4 === false ? "no IQ" : `IQ · ${s.IQ_LLM} through LiteLLM (${s.LLM_PROVIDER})`}`,
    `extras            : ${extras.join(" · ") || "none"}`,
    `stages            : ${stages.join(" | ")}`,
    `hcl charts        : ${hcl.join(" · ") || "-"}`,
    `third-party charts: ${third.join(" · ") || "-"}`,
    `steps             : ${steps.length} (${steps.map(x => x.id).join(" ")})`,
    "",
  ];
  return L.join("\n");
}

// Access to DX layer by layer, from the outside in. Read-only (kubectl port-forward in the background).
export function accessCheck(s){
  const H = s.DX_HOST, NS = s.DX_NS, K = s.openshift ? "oc" : "kubectl";
  const sel = s.INGRESS_CLASS === "traefik" ? "app.kubernetes.io/name=traefik" : "app.kubernetes.io/name=ingress-nginx,app.kubernetes.io/component=controller";
  const L = [
    `H=${H}`,
    `http_ok() { case "$1" in 2??|3??) echo "OK ($1)" ;; *) echo "FAIL (HTTP $1)" ;; esac; }`,
    `http_code() { curl -sk -o /dev/null --max-time 20 -w '%{http_code}' "$@" || true; }   # 000 = no connection`,
    `pf_start() { ${K} "$@" >/dev/null 2>&1 & PF=$!; sleep 4; }                          # port-forward in the background`,
    `pf_stop() { kill $PF 2>/dev/null; wait $PF 2>/dev/null || true; }`,
    `# 1 · DX itself (its HAProxy), without the Ingress, DNS or ports 80/443`,
    `pf_start -n ${NS} port-forward svc/${s.DX_RELEASE}-haproxy 18443:443`,
    `echo "1 · DX (HAProxy, port-forward)          : $(http_ok $(http_code --resolve $H:18443:127.0.0.1 https://$H:18443/wps/portal))"; pf_stop`,
  ];
  if (!s.openshift) L.push(
    `# 2 · The Ingress controller and the route of DX, without DNS or ports 80/443`,
    `read -r INS ISVC _ < <(kubectl get svc -A -l ${sel} --no-headers 2>/dev/null | grep -v admission | head -1) || true`,
    `if [ -n "\${ISVC:-}" ]; then pf_start -n $INS port-forward svc/$ISVC 19443:443`,
    `  echo "2 · Ingress controller $ISVC (port-forward): $(http_ok $(http_code --resolve $H:19443:127.0.0.1 https://$H:19443/wps/portal))"; pf_stop`,
    `else echo "2 · Ingress controller: no Service found with -l ${sel}"; fi`,
    `# 3 · Port 443 of the controller from this machine, without DNS`,
    s.poc ? `IP=127.0.0.1   # the PoC: Traefik/ingress-nginx listen on 80/443 of WSL`
      : `IP=$(kubectl -n "\${INS:-x}" get svc "\${ISVC:-x}" -o jsonpath='{.status.loadBalancer.ingress[0].ip}' 2>/dev/null || true)\n[ -n "$IP" ] || IP=$(kubectl get nodes -o jsonpath='{.items[0].status.addresses[?(@.type=="InternalIP")].address}' || true)`,
    `echo "3 · Port 443 of $IP (no DNS)            : $(http_ok $(http_code --resolve $H:443:$IP https://$H/wps/portal))"`);
  L.push(
    `# ${s.openshift ? 2 : 4} · The real URL (DNS + everything)`,
    `echo "${s.openshift ? 2 : 4} · https://$H ($(getent hosts $H | awk '{print $1}' | head -1 || true))  : $(http_ok $(http_code https://$H/wps/portal))"`,
    s.openshift
      ? `echo "1 fails: DX is not ready (pods, HAProxy) · 1 OK, 2 fails: the Route (oc -n ${NS} get route) or the DNS of $H"`
      : `echo "1 fails: DX is not ready · 1 OK, 2 fails: the route (${exposeFile(s)}) or the controller · 2 OK, 3 fails: ports 80/443 do not reach the controller (firewall, LoadBalancer, WSL) · 3 OK, 4 fails: the DNS or hosts file of $H"\necho "All OK here but the browser of Windows fails (k3s in WSL): docs/troubleshooting.md of the installer, ports 80/443"`);
  return L.join("\n");
}

export const accessStep = (s, lang) => ({lab: "", id: "1-6d", opt: true, manual: "",
  title: lang === "es" ? "Diagnosticar el acceso a DX, capa a capa (opcional)" : "Diagnose the access to DX, layer by layer (optional)",
  note: lang === "es"
    ? "Si el portal no responde: comprueba DX sin el Ingress (kubectl port-forward), después el controlador de Ingress, el puerto 443 y por último el DNS. La primera capa que falla es la que hay que revisar. No cambia nada."
    : "If the portal does not answer: checks DX without the Ingress (kubectl port-forward), then the Ingress controller, port 443 and finally the DNS. The first layer that fails is the one to look at. It changes nothing.",
  cmd: accessCheck(s)});

// support/environment-info.sh: the workstation, tools, cluster, Ingress and access of this installation
export function environmentInfoSh(s){
  const K = s.openshift ? "oc" : "kubectl", NS = s.DX_NS, SH = s.SHARED_NS, H = s.DX_HOST;
  return `#!/usr/bin/env bash
# Workstation, tools, cluster, Ingress and access of this installation, for support. Read-only: it
# changes nothing (the access check uses kubectl port-forward in the background). Generated by the
# HCL DX Compose Installer v${APP_VERSION}; ./install.sh --collect includes its output.
#   support/environment-info.sh                         print the report
#   support/environment-info.sh > environment-info.txt  to send it
set -uo pipefail
cd "$(dirname "$0")/.."
sec() { printf '\\n===== %s =====\\n' "$*"; }
run() { printf '$ %s\\n' "$1"; bash -c "$1" 2>&1 | head -n "\${2:-200}"; }

sec "Installation (BUILD-INFO.txt)"
cat BUILD-INFO.txt 2>/dev/null || echo "BUILD-INFO.txt not found (folder generated before installer 2.6)"

sec "Workstation"
run "date -u"
run "uname -a"
run "grep -E '^(PRETTY_NAME|VERSION_ID)=' /etc/os-release"
if grep -qi microsoft /proc/version 2>/dev/null; then
  echo "WSL: yes"
  run "cat /etc/wsl.conf"
  run "ls /mnt/c/Users/*/.wslconfig 2>/dev/null | head -3 | xargs -r cat"     # networkingMode (NAT / mirrored)
  run "grep -i '${H}' /mnt/c/Windows/System32/drivers/etc/hosts"
else echo "WSL: no"; fi
run "ps -p 1 -o comm="                                                    # systemd or not
run "nproc; free -h; df -h ."

sec "Tools"
run "kubectl version --client"
run "helm version"
run "openssl version; curl --version | head -1; python3 --version"
run "command -v k3s >/dev/null && k3s --version"
${s.openshift ? 'run "oc version"\n' : ""}
sec "Cluster"
run "${K} config current-context"
run "${K} version"
run "${K} get nodes -o wide"
run "${K} get storageclass"
run "${K} get ingressclass"

sec "Ingress controller"
run "${K} get pods,svc -A -o wide -l 'app.kubernetes.io/name in (traefik,ingress-nginx,rke2-ingress-nginx)'"
run "${K} get svc -A --field-selector spec.type=LoadBalancer -o wide"
run "${K} -n kube-system get helmchartconfig,helmchart 2>/dev/null"      # k3s: the configuration of its Traefik

sec "How DX is exposed (${NS})"
run "${K} -n ${NS} get ${s.openshift ? "route" : "ingress,ingressroute.traefik.io,serverstransport.traefik.io,middleware.traefik.io"} -o wide"
run "${K} -n ${NS} get svc ${s.DX_RELEASE}-haproxy -o wide; ${K} -n ${NS} get endpointslices -l kubernetes.io/service-name=${s.DX_RELEASE}-haproxy"
run "${K} -n ${NS} describe ${s.openshift ? "route" : "ingress"} 2>/dev/null" 80

sec "Pods and Helm releases"
run "${K} -n ${NS} get pods -o wide"
run "${K} -n ${SH} get pods -o wide"
run "helm list -A"

sec "Name resolution and ports of this machine"
run "getent hosts ${H}"
run "grep -i '${H}' /etc/hosts"
run "ss -ltn '( sport = :80 or sport = :443 )'"

sec "Access to DX, layer by layer"
${accessCheck(s)}

sec "Recent warnings"
run "${K} get events -A --field-selector type=Warning --sort-by=.lastTimestamp | tail -40"
`;
}

// The support collector also takes BUILD-INFO.txt and the environment report
export function collectorExtras(text){
  return text.replace(/\n# --- README -+\n/, m => `
# --- The installation and the workstation (HCL DX Compose Installer) ---------------------------
HERE="$(cd "$(dirname "$0")" && pwd)"
[ -f "$HERE/../BUILD-INFO.txt" ] && cp "$HERE/../BUILD-INFO.txt" "$OUT/BUILD-INFO.txt"
if [ -x "$HERE/environment-info.sh" ]; then
  info "Workstation, tools, Ingress and access (support/environment-info.sh)"
  "$HERE/environment-info.sh" > "$OUT/environment-info.txt" 2>&1 || warn "environment-info.sh did not finish"
fi
${m}`).replace(/(currentLogs-<release>\.txt and non-running_pod\*\.txt \(only if some pod is not running\)\.)/,
    "$1\nAdded by the installer: BUILD-INFO.txt (what the folder was generated for) and environment-info.txt\n(workstation, tools, Ingress and access to DX layer by layer).");
}
