const MONO = "Consolas", INK = "0B1B3A", BLUE = "0040FF", PINK = "FF0A6C", SOFT = "F2F5FF", LINE = "D6DDF5", GREY = "5B6785";
const run = (text, o = {}) => new TextRun({text, ...o});
const p = (text, o = {}) => new Paragraph({spacing: {after: 120}, ...o, children: [run(text, o.run)]});
const h = (text, level) => new Paragraph({heading: level, spacing: {before: 240, after: 120}, keepNext: true, children: [run(text)]});
const bullet = text => new Paragraph({bullet: {level: 0}, spacing: {after: 80}, children: [run(text)]});
function code(text){
  const lines = String(text).replace(/\t/g, "  ").split("\n");
  return lines.map((l, i) => new Paragraph({
    shading: {type: ShadingType.CLEAR, fill: SOFT, color: "auto"},
    spacing: {before: i === 0 ? 60 : 0, after: i === lines.length - 1 ? 160 : 0, line: 240},
    indent: {left: 120, right: 120}, keepLines: true,
    children: [run(l || " ", {font: MONO, size: 17})],
  }));
}
const box = (text, fill, bold = true) => new Paragraph({shading: {type: ShadingType.CLEAR, fill, color: "auto"}, spacing: {before: 120, after: 200}, indent: {left: 120, right: 120},
  children: [run(text, {bold})]});
const cell = (text, o = {}) => new TableCell({
  shading: o.head ? {type: ShadingType.CLEAR, fill: BLUE, color: "auto"} : undefined,
  margins: {top: 60, bottom: 60, left: 100, right: 100},
  width: o.w ? {size: o.w, type: WidthType.PERCENTAGE} : undefined,
  children: [new Paragraph({children: [run(String(text), {bold: !!o.head, color: o.head ? "FFFFFF" : INK, font: o.mono ? MONO : undefined, size: o.mono ? 16 : 20})]})],
});
function table(rows, widths, o = {}){
  const border = {style: BorderStyle.SINGLE, size: 4, color: LINE};
  return new Table({
    width: {size: 100, type: WidthType.PERCENTAGE},
    borders: {top: border, bottom: border, left: border, right: border, insideHorizontal: border, insideVertical: border},
    rows: rows.map((r, i) => new TableRow({tableHeader: i === 0, children: r.map((c, j) => cell(c, {head: i === 0, w: widths[j], mono: i > 0 && o.mono && o.mono.includes(j)}))})),
  });
}
const secretNames = cmd => [...new Set([...cmd.matchAll(/create secret (?:generic|tls|docker-registry) ([\w.-]+)/g)].map(m => m[1]))];

export async function buildWord(gen, lang, summaryRows, {mask = true, as = "blob"} = {}){
  const t = W[lang] || W.en, talk = TALK[lang] || TALK.en, names = STAGES[lang] || STAGES.en;
  const {s, files} = gen, prep = gen.prep || [], demo = gen.demo || gen.steps;
  const values = mask ? secretValues(s) : [];
  const m = x => mask ? maskText(String(x), values) : String(x);
  const md = x => m(String(x).replace(/\*\*|\*|`/g, ""));
  const body = [];

  // Cover
  body.push(new Paragraph({spacing: {before: 1600, after: 120}, children: [run("EUROPESIP", {bold: true, color: PINK, size: 24, characterSpacing: 40})]}));
  body.push(new Paragraph({spacing: {after: 120}, children: [run(t.title, {bold: true, size: 60, color: INK})]}));
  body.push(new Paragraph({spacing: {after: 120}, children: [run(t.product, {size: 34, color: BLUE})]}));
  body.push(new Paragraph({spacing: {after: 600}, children: [run(`https://${s.DX_HOST} · ${new Date().toISOString().slice(0, 10)}`, {color: GREY})]}));
  body.push(table([[lang === "es" ? "Opción" : "Choice", lang === "es" ? "Valor" : "Value"], ...summaryRows.filter(([k, v]) => v).map(([k, v]) => [k, m(v)])], [32, 68]));
  body.push(box(mask ? t.warnMasked : t.warnPlain, mask ? "EAF7EE" : "FDECEC"));
  body.push(p(t.sub, {run: {color: GREY, size: 18}}));
  body.push(new Paragraph({children: [new PageBreak()]}));
  body.push(h(t.toc, HeadingLevel.HEADING_1));
  body.push(new TableOfContents(t.toc, {hyperlink: true, headingStyleRange: "1-2"}));
  body.push(p(t.tocNote, {run: {italics: true, color: GREY}}));
  body.push(new Paragraph({children: [new PageBreak()]}));

  // At a glance
  body.push(h(t.s0, HeadingLevel.HEADING_1));
  body.push(table([[t.stageCol, t.timeCol, t.showCol], ...talk.map((x, i) => [`${i} · ${names[i]}`, x.time, x.show])], [38, 12, 50]));

  // Preparation
  body.push(h(t.s1, HeadingLevel.HEADING_1));
  body.push(p(t.s1T));
  t.s1Need.forEach(x => body.push(bullet(x)));
  body.push(...code(t.s1Cmd));
  for (const st of prep) {
    body.push(new Paragraph({spacing: {before: 160, after: 60}, keepNext: true, children: [run(`${st.id} · ${st.title}`, {bold: true, color: INK})]}));
    if (st.note) body.push(p(md(st.note), {run: {color: GREY}}));
    body.push(...code(m(st.cmd)));
  }
  body.push(box("✔ " + t.s1Ready, "EAF7EE"));

  // The demo
  body.push(new Paragraph({children: [new PageBreak()]}));
  body.push(h(t.s2, HeadingLevel.HEADING_1));
  body.push(p(t.s2T));
  body.push(...code(t.s2Cmd));
  for (let n = 0; n <= 5; n++) {
    const list = demo.filter(x => x.stage === n);
    if (!list.length) continue;
    body.push(new Paragraph({children: [new PageBreak()]}));
    body.push(h(`${n} · ${names[n]}`, HeadingLevel.HEADING_1));
    body.push(p(`⏱ ${talk[n].time} · ${talk[n].show}`, {run: {color: BLUE, bold: true}}));
    body.push(h(t.tell, HeadingLevel.HEADING_2));
    talk[n].points.forEach(x => body.push(bullet(x)));
    body.push(h(t.steps, HeadingLevel.HEADING_2));
    for (const st of list) {
      body.push(new Paragraph({spacing: {before: 200, after: 80}, keepNext: true, children: [
        run(`${st.id} · ${st.title}`, {bold: true, color: INK, size: 23}),
        ...(st.opt ? [run(`  (${t.opt})`, {italics: true, color: GREY})] : [])]}));
      if (st.note) body.push(p(md(st.note), {run: {color: GREY}}));
      body.push(...code(m(st.cmd)));
      const sec = secretNames(st.cmd);
      if (sec.length || /apply -f \S*secrets\.yaml/.test(st.cmd)) {
        const fromFiles = filesOfStep(st, files).filter(f => /secret/i.test(f)).flatMap(f => [...files[f].text.matchAll(/^\s*name:\s*([\w.-]+)/gm)].map(x => x[1]));
        body.push(p(`🔑 ${t.secrets}: ${[...new Set([...fromFiles, ...sec])].join(", ")}`, {run: {bold: true, color: PINK}}));
      }
      for (const f of filesOfStep(st, files)) {
        const ch = keyChanges(files[f].text);
        if (!ch.length) continue;
        body.push(p(`${t.look} · ${f}`, {run: {bold: true}, keepNext: true}));
        body.push(table([[t.used, t.was], ...ch.slice(0, 25).map(c => [m(c.line), c.was ? m(c.was) : t.newv])], [55, 45], {mono: [0, 1]}));
        body.push(p(""));
      }
      if (st.manual) body.push(box(`${t.manual}: ${md(st.manual)}`, "FFF4E5"));
    }
  }

  // Closing
  body.push(h(t.end, HeadingLevel.HEADING_1));
  body.push(p(t.endT(`https://${s.DX_HOST}/wps/portal`)));
  body.push(p(t.clean));

  // Appendices
  body.push(new Paragraph({children: [new PageBreak()]}));
  body.push(h(t.a1, HeadingLevel.HEADING_1));
  body.push(p(t.a1T));
  for (const st of [...prep, ...demo].filter(isSecretStep)) { body.push(h(`${st.id} · ${st.title}`, HeadingLevel.HEADING_2)); body.push(...code(m(st.cmd))); }
  body.push(p(t.litellm)); body.push(...code(mask ? "********" : gen.litellmKey || ""));
  body.push(new Paragraph({children: [new PageBreak()]}));
  body.push(h(t.a2, HeadingLevel.HEADING_1));
  body.push(p(t.a2T));
  for (const [path, f] of Object.entries(files)) {
    if (!/\.(ya?ml|properties|ldif|json)$/i.test(path)) continue;
    body.push(h(path, HeadingLevel.HEADING_2));
    const src = sourceOf(f.text);
    if (src) body.push(p(`${t.from}: ${src}`, {run: {italics: true, color: GREY}}));
    body.push(...code(m(f.text)));
  }

  const doc = new Document({
    creator: "HCL DX Compose Installer · EUROPESIP", title: `${t.title} · ${t.product}`, description: "https://" + s.DX_HOST,
    features: {updateFields: true},
    styles: {
      default: {document: {run: {font: "Calibri", size: 21, color: INK}}},
      paragraphStyles: [
        {id: "Heading1", name: "Heading 1", basedOn: "Normal", next: "Normal", quickFormat: true, run: {size: 36, bold: true, color: BLUE}, paragraph: {spacing: {before: 360, after: 160}}},
        {id: "Heading2", name: "Heading 2", basedOn: "Normal", next: "Normal", quickFormat: true, run: {size: 26, bold: true, color: INK}, paragraph: {spacing: {before: 240, after: 100}}},
      ],
    },
    sections: [{
      properties: {page: {margin: {top: 1000, bottom: 1000, left: 1000, right: 1000}}},
      headers: {default: new Header({children: [new Paragraph({alignment: AlignmentType.RIGHT, children: [run("EUROPESIP · HCL DX Compose", {size: 16, color: GREY})]})]})},
      footers: {default: new Footer({children: [new Paragraph({alignment: AlignmentType.CENTER, children: [
        run(t.footer, {size: 16, color: GREY}), new TextRun({children: [PageNumber.CURRENT], size: 16, color: GREY})]})]})},
      children: body,
    }],
  });
  return as === "buffer" ? Packer.toBuffer(doc) : Packer.toBlob(doc);
}
