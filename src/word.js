const MONO = "Consolas", INK = "15123B", ACCENT = "4F2BD9", SOFT = "F3F1FB", LINE = "D9D5EE";
const p = (text, o = {}) => new Paragraph({spacing: {after: 120}, ...o, children: [new TextRun({text, ...o.run})]});
const h = (text, level) => new Paragraph({heading: level, spacing: {before: 240, after: 120}, children: [new TextRun({text})]});
const bullet = text => new Paragraph({bullet: {level: 0}, spacing: {after: 60}, children: [new TextRun(text)]});
function code(text){
  const lines = String(text).replace(/\t/g, "  ").split("\n");
  return lines.map((l, i) => new Paragraph({
    shading: {type: ShadingType.CLEAR, fill: SOFT, color: "auto"},
    spacing: {before: i === 0 ? 60 : 0, after: i === lines.length - 1 ? 160 : 0, line: 240},
    indent: {left: 120, right: 120},
    children: [new TextRun({text: l || " ", font: MONO, size: 17})],
  }));
}
const cell = (text, o = {}) => new TableCell({
  shading: o.head ? {type: ShadingType.CLEAR, fill: ACCENT, color: "auto"} : undefined,
  margins: {top: 60, bottom: 60, left: 100, right: 100},
  width: o.w ? {size: o.w, type: WidthType.PERCENTAGE} : undefined,
  children: [new Paragraph({children: [new TextRun({text: String(text), bold: !!o.head, color: o.head ? "FFFFFF" : INK,
    font: o.mono ? MONO : undefined, size: o.mono ? 16 : 20})]})],
});
function table(rows, widths, o = {}){
  const border = {style: BorderStyle.SINGLE, size: 4, color: LINE};
  return new Table({
    width: {size: 100, type: WidthType.PERCENTAGE},
    borders: {top: border, bottom: border, left: border, right: border, insideHorizontal: border, insideVertical: border},
    rows: rows.map((r, i) => new TableRow({tableHeader: i === 0, children: r.map((c, j) => cell(c, {head: i === 0, w: widths[j], mono: i > 0 && o.mono && o.mono.includes(j)}))})),
  });
}

export async function buildWord(gen, lang, summaryRows, {mask = true, as = "blob"} = {}){
  const t = W[lang] || W.en, {s, steps, files} = gen;
  const values = mask ? secretValues(s) : [];
  const m = x => mask ? maskText(String(x), values) : String(x);
  const body = [];

  body.push(new Paragraph({spacing: {before: 1800, after: 200}, children: [new TextRun({text: t.title, bold: true, size: 52, color: INK})]}));
  body.push(new Paragraph({spacing: {after: 120}, children: [new TextRun({text: "https://" + s.DX_HOST, size: 32, color: ACCENT})]}));
  body.push(new Paragraph({spacing: {after: 600}, children: [new TextRun({text: `${t.sub} · ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC`, color: "6B6790"})]}));
  body.push(new Paragraph({shading: {type: ShadingType.CLEAR, fill: mask ? "EAF7EE" : "FDECEC", color: "auto"}, spacing: {after: 200},
    children: [new TextRun({text: mask ? t.warnMasked : t.warnPlain, bold: true})]}));
  body.push(new Paragraph({children: [new PageBreak()]}));
  body.push(h(t.toc, HeadingLevel.HEADING_1));
  body.push(new TableOfContents(t.toc, {hyperlink: true, headingStyleRange: "1-2"}));
  body.push(p(t.tocNote, {run: {italics: true, color: "6B6790"}}));
  body.push(new Paragraph({children: [new PageBreak()]}));

  body.push(h(t.s1, HeadingLevel.HEADING_1));
  body.push(table([[t.choice, t.value], ...summaryRows.map(([k, v]) => [k, m(v)])], [35, 65]));

  body.push(h(t.s2, HeadingLevel.HEADING_1));
  t.pre.forEach(x => body.push(bullet(x)));
  body.push(p(t.run));
  body.push(...code(t.runCmds.join("\n")));

  body.push(h(t.s3, HeadingLevel.HEADING_1));
  body.push(p(t.s3T));
  const sec = steps.filter(isSecretStep);
  for (const st of sec) { body.push(h(`${st.id} · ${st.title}`, HeadingLevel.HEADING_2)); body.push(...code(m(st.cmd))); }
  if (s.lab3 || s.deps.llm) { body.push(p(t.litellm)); body.push(...code(mask ? "********" : gen.litellmKey || "")); }
  body.push(h(t.secretFiles, HeadingLevel.HEADING_2));
  const secFiles = Object.keys(files).filter(f => /secret/i.test(f));
  if (secFiles.length) secFiles.forEach(f => body.push(bullet(f))); else body.push(p(t.none));

  body.push(h(t.s4, HeadingLevel.HEADING_1));
  let lab = "";
  for (const st of steps) {
    if (st.lab !== lab) { lab = st.lab; body.push(h(lab, HeadingLevel.HEADING_2)); }
    body.push(new Paragraph({spacing: {before: 160, after: 80}, keepNext: true, children: [
      new TextRun({text: `${st.id} · ${st.title}`, bold: true, color: INK}),
      ...(st.opt ? [new TextRun({text: `  (${t.opt})`, italics: true, color: "6B6790"})] : [])]}));
    if (st.note) body.push(p(m(st.note.replace(/\*\*|`/g, ""))));
    body.push(...code(m(st.cmd)));
    if (st.manual) body.push(p(`${t.manual}: ${m(st.manual.replace(/\*\*|\*|`/g, ""))}`, {run: {bold: true}}));
  }
  body.push(p(`${t.end} https://${s.DX_HOST}/wps/portal`, {run: {bold: true}}));

  body.push(new Paragraph({children: [new PageBreak()]}));
  body.push(h(t.s5, HeadingLevel.HEADING_1));
  body.push(p(t.s5T));
  for (const [path, f] of Object.entries(files)) {
    const ch = keyChanges(f.text);
    if (!ch.length) continue;
    body.push(h(path, HeadingLevel.HEADING_2));
    body.push(p(`${t.from}: ${sourceOf(f.text)}`, {run: {italics: true, color: "6B6790"}}));
    body.push(table([[t.used, t.was], ...ch.map(c => [m(c.line), c.was ? m(c.was) : t.newv])], [55, 45], {mono: [0, 1]}));
  }

  body.push(new Paragraph({children: [new PageBreak()]}));
  body.push(h(t.s6, HeadingLevel.HEADING_1));
  body.push(p(t.s6T));
  for (const [path, f] of Object.entries(files)) {
    if (!/\.(ya?ml|properties|ldif|json)$/i.test(path)) continue;
    body.push(h(path, HeadingLevel.HEADING_2));
    body.push(...code(m(f.text)));
  }

  const doc = new Document({
    creator: "HCL DX Compose Installer", title: t.title, description: "https://" + s.DX_HOST,
    features: {updateFields: true},
    styles: {
      default: {document: {run: {font: "Calibri", size: 21, color: INK}}},
      paragraphStyles: [
        {id: "Heading1", name: "Heading 1", basedOn: "Normal", next: "Normal", quickFormat: true, run: {size: 34, bold: true, color: ACCENT}, paragraph: {spacing: {before: 360, after: 160}}},
        {id: "Heading2", name: "Heading 2", basedOn: "Normal", next: "Normal", quickFormat: true, run: {size: 26, bold: true, color: INK}, paragraph: {spacing: {before: 240, after: 100}}},
      ],
    },
    sections: [{
      properties: {page: {margin: {top: 1000, bottom: 1000, left: 1000, right: 1000}}},
      footers: {default: new Footer({children: [new Paragraph({alignment: AlignmentType.CENTER, children: [
        new TextRun({text: t.footer, size: 16, color: "6B6790"}), new TextRun({children: [PageNumber.CURRENT], size: 16, color: "6B6790"})]})]})},
      children: body,
    }],
  });
  return as === "buffer" ? Packer.toBuffer(doc) : Packer.toBlob(doc);
}
